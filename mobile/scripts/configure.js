'use strict';
// Validates the build environment and writes www/runtime-config.js for the offline page.
// Run before every `cap add` / `cap sync` (npm scripts do this automatically).
const fs = require('node:fs');
const path = require('node:path');
const { serverFromEnv, appIdFromEnv } = require('../lib/server-url');

try {
  const server = serverFromEnv();
  const appId = appIdFromEnv();
  const out = path.join(__dirname, '..', 'www', 'runtime-config.js');
  fs.writeFileSync(out, `// Generated by scripts/configure.js. Do not edit or commit.\nwindow.FORMCLUB_SERVER_URL = ${JSON.stringify(server ? server.url : '')};\n`);
  console.log(`appId: ${appId}`);
  if (!server) console.warn('UYARI: FORMCLUB_SERVER_URL yok. Uygulama yalnızca kurulum sayfasını gösterir.');
  else console.log(`sunucu: ${server.url}${server.cleartext ? ' (http, yalnızca yerel geliştirme)' : ''}`);
} catch (error) {
  console.error('Yapılandırma hatası: ' + error.message);
  process.exit(1);
}
